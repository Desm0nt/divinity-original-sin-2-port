enum { T_SHADER, T_VB, T_IB, T_VFMT, T_BLEND, T_DS, T_RASTER, T_N };
static const uint32_t k_tab[T_N] = {NRST_T_SHADER, NRST_T_VB, NRST_T_IB, NRST_T_VFMT, NRST_T_BLEND, NRST_T_DS, NRST_T_RASTER};
static const uint32_t k_esz[T_N] = {0x60, 0x68, 0x58, 0x80, 0x20, 0x20, 0x18};
static uint32_t tab_at(int t) { return A_TAB + (uint32_t)t * TAB_STRIDE; }
static uint64_t g_special;
static uint64_t handle(int t, int kind) {
    const uint32_t per = (uint32_t)(r64(A_R + k_tab[t] + 0x10) & 0xffffffff), page = (uint32_t)(rnd() % 4), off = per ? (uint32_t)(rnd() % per) : 0;
    const uint32_t idx = page * per + off, T = tab_at(t);
    uint32_t gen; memcpy(&gen, g_arena + T + 0x40 + 0x20 * page + 4 * off, 4);
    if (kind == 0) return 0;
    if (kind == 1) return (uint64_t)idx;
    if (kind == 2) return (rnd() & 0x3ff) << 54 | (uint64_t)((gen ^ 5) & 0x3fffff) << 32 | idx;
    return (rnd() & 0x3ff) << 54 | (uint64_t)(gen & 0x3fffff) << 32 | idx;
}
static uint64_t pick(int t) { const int r = (int)(rnd() % 16); return handle(t, r == 0 ? 0 : r == 1 ? 1 : r == 2 ? 2 : 3); }
static void world(void) {
    for (uint32_t i = 0; i < ARENA; i += 8) w64(i, rnd());
    w64(A_LIST + 0x38, GA + A_R);
    w64(A_R + NRST_R_DEV, GA + A_DEV); w64(A_DEV + NRST_DEV_CTX, GA + A_CTX); w64(A_DEV + NRST_DEV_FRAME, rnd() & 0xffffff);
    for (int t = 0; t < T_N; t++) {
        const uint32_t T = tab_at(t), per = 1 + (uint32_t)(rnd() % 8);
        w64(A_R + k_tab[t], GA + T); w64(A_R + k_tab[t] + 8, GA + T + 0x20); w32(A_R + k_tab[t] + 0x10, per);
        for (int p = 0; p < 4; p++) {
            w64(T + 8 * p, GA + T + 0x100 + 0x400 * p); w64(T + 0x20 + 8 * p, GA + T + 0x40 + 0x20 * p);
            for (int k = 0; k < 8; k++) w32(T + 0x40 + 0x20 * p + 4 * k, 1 + (uint32_t)(rnd() % 0x3ffffe));
            for (uint32_t k = 0; k < 8; k++) {
                const uint32_t e = T + 0x100 + 0x400 * p + k * k_esz[t];
                if (t == T_SHADER && rnd() % 4 == 0) w64(e + 8 + 8 * (rnd() % 2), 0);
                if (t == T_VB && rnd() % 6 == 0) w64(e, 0);
                if (t == T_VFMT) { if (rnd() % 2) w32(e + 0x1c, 0); if (rnd() % 2) w32(e + 0x18, 0); }
            }
        }
    }
    g_special = rnd() % 3 ? 0x7fff00001234ull : handle(T_BLEND, 3);
}
static void packet(void) {
    uint8_t *R = g_arena + A_R, *P = g_arena + A_PKT;
    const uint64_t sh = pick(T_SHADER), ds = pick(T_DS), ra = pick(T_RASTER), bl = rnd() % 8 == 0 ? g_special : pick(T_BLEND), vf = pick(T_VFMT);
    w64(A_PKT + 8, sh); w64(A_PKT + 0x10, ds); w32(A_PKT + 0x18, (uint32_t)(rnd() % 4)); w64(A_PKT + 0x20, ra); w64(A_PKT + 0x28, bl); w64(A_PKT + 0x30, vf);
    for (int k = 0; k < 3; k++) w64(A_PKT + 0x38 + 8 * k, k && rnd() % 2 ? 0 : pick(T_VB));
    w64(A_PKT + 0x50, rnd() % 4 ? (rnd() & ~0xffffffffull) | (rnd() % (4 * (r64(A_R + NRST_T_IB + 0x10) & 0xffffffff))) : 0);
    P[0x58] = (uint8_t)(rnd() % 10);
    w64(A_PKT + 0x60, rnd() % 3 ? 0 : GA + A_CNT);
    static const float fa[6] = {-1.f, 0.f, 0.5f, -0.f, 0.25f, 1.f}; float a = fa[rnd() % 6]; memcpy(P + 0x68, &a, 4);
    static const uint32_t same[][2] = {{NRST_R_SHADER, 8}, {NRST_R_DS, 0x10}, {NRST_R_RASTER, 0x20}, {NRST_R_BLEND, 0x28}, {NRST_R_VFMT, 0x30},
                                       {NRST_R_VB, 0x38}, {NRST_R_VB + 8, 0x40}, {NRST_R_VB + 16, 0x48}, {NRST_R_IB, 0x50}, {NRST_R_REN_Q, 0x60}};
    for (unsigned i = 0; i < sizeof same / sizeof same[0]; i++) if (rnd() % 2) memcpy(R + same[i][0], P + same[i][1], 8);
    if (rnd() % 2) memcpy(R + NRST_R_REF, P + 0x18, 4);
    if (rnd() % 2) R[NRST_R_PRIM] = P[0x58];
    if (rnd() % 2) memcpy(R + NRST_R_ALPHA, P + 0x68, 4);
    R[NRST_R_REN_NEED] = (uint8_t)(rnd() % 3);
    for (int k = 0; k < 3; k++) w64(A_R + NRST_R_VB_DIRTY + 8 * k, rnd() % 3 ? 0 : rnd());
    w64(A_R + NRST_R_IB_FIRST, rnd() % 3 ? 0 : rnd());
    w32(A_R + NRST_R_BLEND_MASK, rnd() % 2 ? 0xffffffffu : (uint32_t)rnd());
    for (int i = 0; i < 8; i++) w64(A_R + NRST_R_RT + 8 * i, rnd() % 2 ? 0 : rnd());
}

// ---- the command stream ----
enum { STREAM = 1 << 22 };
typedef struct { uint8_t *b; uint32_t used; } stream;
// What rec() / cmd_alloc() do per record besides the copy (hle_nvn.c): NBS_BEFORE / NBD_FOREIGN / NBF_REC / the threads counter / the native-draw
// test / the segment test / the command-stats test / NBF_DRAW / NBS_RAW: flag loads that stand for those globals and thread-locals.
static volatile int vf_nbd, vf_nbf, vf_thr, vf_nd, vf_cs, vf_raw; static volatile uint64_t vf_cnt;
static inline void fe_alloc_hooks(void) { if (vf_nbd) vf_cnt++; if (vf_nbf) vf_cnt++; if (vf_thr) vf_cnt++; if (vf_nd) vf_cnt++; if (vf_cs) vf_cnt++; if (vf_raw) vf_cnt++; }
static uint8_t *s_put(stream *s, uint32_t op, uint32_t payload) {   // as rec(): header + zeroed payload, 8-aligned
    fe_alloc_hooks();
    const uint32_t sz = (8 + payload + 7) & ~7u;
    if (s->used + sz + 8 > STREAM) { printf("stream full\n"); exit(2); }
    uint8_t *p = s->b + s->used; const uint32_t h[2] = {op, sz}; memcpy(p, h, 8); memset(p + 8, 0, sz - 8); s->used += sz; return p + 8;
}

// ---- the NB-13a front end (nvn_nb_state.inc, one thread, one command buffer) ----
typedef struct { nbs_state sh; int pend; uint32_t psize; uint8_t prec[NBS_REC_MAX]; uint8_t out[NBS_PAYLOAD_MAX]; uint32_t epoch_next; int no_unknown; } front;
static void fe_write(front *f, stream *s) { const uint32_t n = nbs_pack(&f->sh, f->out, sizeof f->out); if (n) memcpy(s_put(s, OP_X_NB_STATE, n), f->out, n); }
static void fe_settle(front *f, stream *s) {
    if (!f->pend) return;
    f->pend = 0;
    if (nbs_capture(&f->sh, f->prec, f->psize) >= 0) return;
    fe_write(f, s);
    uint32_t op; memcpy(&op, f->prec, 4); memcpy(s_put(s, op, f->psize - 8), f->prec + 8, f->psize - 8);
    uint32_t key; const int k = nbs_kind(op, f->prec + 8, f->psize - 8, &key); nbs_unknown(&f->sh, k >= 0 ? 1u << k : nbs_op_kinds(op));
}
static void fe_flush(front *f, stream *s) { fe_settle(f, s); fe_write(f, s); }
static void fe_epoch(front *f, stream *s) { fe_flush(f, s); uint32_t e = f->epoch_next++; if (!e) e = f->epoch_next++; nbs_new_epoch(&f->sh, e); }
// a state record written by a body: inside a taken bracket captured (filed at the next call), else plain (flush, record, kind unknown)
static void fe_state(front *f, stream *s, int taken, uint32_t op, const void *pl, uint32_t n) {
    fe_settle(f, s);
    const uint32_t size = (8 + n + 7) & ~7u;
    if (taken && size <= NBS_REC_MAX) {
        f->pend = 1; f->psize = size; memset(f->prec, 0, size); const uint32_t h[2] = {op, size}; memcpy(f->prec, h, 8); memcpy(f->prec + 8, pl, n);
        return;
    }
    fe_flush(f, s);
    memcpy(s_put(s, op, n), pl, n);
    uint32_t key; const int k = nbs_kind(op, pl, n, &key); nbs_unknown(&f->sh, k >= 0 ? 1u << k : nbs_op_kinds(op));
}
// any other record (draw, ...): what is pending goes out first
static uint8_t *fe_other(front *f, stream *s, uint32_t op, uint32_t n) { fe_settle(f, s); if (f->sh.dirty) fe_write(f, s); return s_put(s, op, n); }

// ---- the bodies (hle_nvn.c), writing records through the front end ----
typedef struct { blend_st b; uint8_t pad[64]; } lblend;   // the default path's stack objects
typedef struct { color_st c; uint8_t pad[64]; } lcolor;
static void bind_state(front *f, stream *s, int taken, int kind, const void *st, size_t n) { p_bind_state r; memset(&r, 0, sizeof r); r.kind = kind; memcpy(r.bytes, st, n); fe_state(f, s, taken, OP_BIND_STATE, &r, sizeof r); }
static void s1_exec(front *f, stream *s, const nrst_op *op, int n, int drop) {
    lblend lb; lcolor lc; memset(&lb, 0, sizeof lb); memset(&lc, 0, sizeof lc);
    for (int k = 0; k < n; k++) {
        const nrst_op *o = &op[k];
        void *p = o->p == NRST_LOCAL_BLEND ? (void *)&lb : o->p == NRST_LOCAL_COLOR ? (void *)&lc : (o->p ? (void *)NRST_PTR(o->p) : NULL);
        if (k == drop) continue;   // injected: the body's record left out
        switch (o->fn) {
        case NRST_F_PROGRAM: { p_bind_program r; memset(&r, 0, sizeof r); r.prog = (const prog_t *)(uintptr_t)o->p; r.stages = o->i; fe_state(f, s, 1, OP_BIND_PROGRAM, &r, sizeof r); break; }
        case NRST_F_DS: bind_state(f, s, 1, 5, p, sizeof(ds_st)); break;
        case NRST_F_STENCIL_VMASK: { p_stencil r = {o->i, o->j, 0, 0, 0}; fe_state(f, s, 1, OP_STENCIL, &r, sizeof r); break; }
        case NRST_F_STENCIL_MASK: { p_stencil r = {o->i, 0, o->j, 0, 1}; fe_state(f, s, 1, OP_STENCIL, &r, sizeof r); break; }
        case NRST_F_STENCIL_REF: { p_stencil r = {o->i, 0, 0, o->j, 2}; fe_state(f, s, 1, OP_STENCIL, &r, sizeof r); break; }
        case NRST_F_POLY: bind_state(f, s, 1, 4, p, sizeof(poly_st)); break;
        case NRST_F_BLEND_DEF: b_blend_def(p); break;
        case NRST_F_BLEND: bind_state(f, s, 1, 0, p, sizeof(blend_st)); break;
        case NRST_F_COLOR_DEF: b_color_def(p); break;
        case NRST_F_COLOR_ATEST: b_color_atest(p, o->i); break;
        case NRST_F_COLOR: bind_state(f, s, 1, 1, p, sizeof(color_st)); break;
        case NRST_F_BLEND_TARGET: b_blend_target(p, o->i); break;
        case NRST_F_COLOR_BLEND: b_color_blend(p, o->i, (uint32_t)o->j); break;
        case NRST_F_VATTR: { p_bind_vattr r; memset(&r, 0, sizeof r); r.n = o->i; memcpy(r.st, p, 4 * (size_t)o->i); fe_state(f, s, 1, OP_BIND_VATTR, &r, offsetof(p_bind_vattr, st) + 4 * (size_t)o->i); break; }
        case NRST_F_VSTREAM: { p_bind_vstream r; memset(&r, 0, sizeof r); r.n = o->i; memcpy(r.st, p, 8 * (size_t)o->i); fe_state(f, s, 1, OP_BIND_VSTREAM, &r, offsetof(p_bind_vstream, st) + 8 * (size_t)o->i); break; }
        case NRST_F_VB: { p_bind_vbuf r; memset(&r, 0, sizeof r); r.first = o->i; r.n = 1; r.r[0].address = o->p; r.r[0].size = o->q; fe_state(f, s, 1, OP_BIND_VBUF, &r, offsetof(p_bind_vbuf, r) + sizeof r.r[0]); break; }
        case NRST_F_ALPHA_REF: { p_alpha_ref r = {o->f, 0}; fe_state(f, s, 1, OP_X_ALPHA_REF, &r, sizeof r); break; }
        default: break;   // REN / REN_COND: no state record (DM_GFX_COND_RENDER off)
        }
    }
}
// S3 (nvn_nr_state3.inc mode 4): build, write back, flush, one record, the kinds unknown
static nr3_b g_b;
static int g_no_writeback;
static int s3_exec(front *f, stream *s, const nrst_op *op, int n, uint32_t flags, uint32_t seq, int flip) {
    if (!nr3_build(&g_b, op, n)) return 0;
    if (g_mut_build)   // mutation: the blend binds read the object's memory, not the copy the packet's setters changed
        for (int k = 0; k < n; k++) if (op[k].fn == NRST_F_BLEND && op[k].p > 2) { const uint64_t v = nr3_rd(op[k].p, 8); g_b.r.blendb[v & 7] = v; g_b.r.blend |= (uint16_t)(1u << (v & 7)); }
    g_b.r.flags = (uint8_t)flags; g_b.r.seq = seq;
    if (!flags) { if (!g_no_writeback) nr3_writeback(&g_b); fe_flush(f, s); }
    const uint32_t sz = nr3_size(&g_b.r);
    uint8_t *p = fe_other(f, s, OP_X_NR_STATE, sz);
    nr3_put(&g_b.r, p);
    if (flip >= 0 && sz > 16) p[16 + (uint32_t)flip % (sz - 16)] ^= (uint8_t)(1u << (flip % 7));   // injected: a bit of a part
    if (!flags && !f->no_unknown) { fe_settle(f, s); nbs_unknown(&f->sh, nr3_kinds(&g_b.r)); }
    return 1;
}

