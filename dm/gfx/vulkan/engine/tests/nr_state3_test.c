static void m_rec(model *m, uint32_t op, const uint8_t *p, uint32_t n) {
    switch (op) {
    case OP_BIND_PROGRAM: { p_bind_program a; memcpy(&a, p, sizeof a); m_bind(m->shader, &m->missing, (uint64_t)(uintptr_t)a.prog, a.stages); break; }
    case OP_BIND_STATE: { p_bind_state a; memcpy(&a, p, sizeof a);
        switch (a.kind) { case 0: { blend_st b; memcpy(&b, a.bytes, sizeof b); m->blend[b.target] = b; break; } case 1: memcpy(&m->color, a.bytes, sizeof m->color); break;
        case 2: memcpy(&m->mask, a.bytes, sizeof m->mask); break; case 3: memcpy(&m->ms, a.bytes, sizeof m->ms); break; case 4: memcpy(&m->poly, a.bytes, sizeof m->poly); break;
        case 5: memcpy(&m->ds, a.bytes, sizeof m->ds); break; default: CHECK(0, "bind state kind %d", a.kind); } break; }
    case OP_BIND_VATTR: { p_bind_vattr a; memset(&a, 0, sizeof a); memcpy(&a, p, n < sizeof a ? n : sizeof a); CHECK(xbg_vertex_attributes_replace(m->attrib, a.st, a.n) == 0, "vattr"); break; }
    case OP_BIND_VSTREAM: { p_bind_vstream a; memset(&a, 0, sizeof a); memcpy(&a, p, n < sizeof a ? n : sizeof a); memcpy(m->stream + a.first, a.st, (size_t)a.n * sizeof(vs_st)); break; }
    case OP_BIND_VBUF: { p_bind_vbuf a; memset(&a, 0, sizeof a); memcpy(&a, p, n < sizeof a ? n : sizeof a); memcpy(m->vb + a.first, a.r, (size_t)a.n * sizeof(NVNbufferRange)); break; }
    case OP_STENCIL: { p_stencil a; memcpy(&a, p, sizeof a); for (unsigned i = 0; i < 2; i++) if (a.face & (1 << i)) { if (a.which == 0) m->stencil_compare[i] = a.value_mask; else if (a.which == 1) m->stencil_write[i] = a.mask; else m->stencil_ref[i] = a.ref; } break; }
    case OP_X_ALPHA_REF: { p_alpha_ref a; memcpy(&a, p, sizeof a); m->alpha_ref = a.ref; break; }
    case OP_BLEND_COLOR: memcpy(m->blend_color, p, 16); break;
    case OP_POLY_OFFSET: memcpy(m->bias, p, 12); break;
    case OP_VIEWPORTS: { p_viewports a; memset(&a, 0, sizeof a); memcpy(&a, p, n < sizeof a ? n : sizeof a); memcpy(m->vp, a.v[0], 16); break; }
    case OP_SCISSOR: memcpy(m->sc, p, 16); break;
    case OP_DEPTH_RANGE: memcpy(&m->dmin, p, 4); memcpy(&m->dmax, p + 4, 4); break;
    default: break;
    }
}
typedef struct { uint32_t epoch; const uint8_t *c; } bdef;
static bdef g_defs[NBS_KINDS][NBS_MAX_IDS];
typedef struct { unsigned long long checks, bad, unpaired, badf[NR3_C_N], draws, nbstate, nrstate, miss, badparse; int lastf; } bstats;
static snap g_want; static uint32_t g_want_seq; static int g_want_on;
// What execute()'s loop does per record besides its case (xbg_game.cpp): the NB-17a stop compare, the budget, the async poll test, the
// arena test, the mid-chunk test, command_available's range test, the header checks, nbpipe::mark (nbs_kind), the pass-graph test.
// Volatile flags stand for the globals it loads; every record (old: OP_X_NB_STATE and each record it nests; new: OP_X_NR_STATE) pays it.
static volatile uint64_t vg_stop, vg_async, vg_rec, vg_used, vg_limit = ~0ull, vg_mid, vg_lo, vg_bytes = ~0ull, vg_pipe = 1, vg_pgraph, vg_dirty;
static uint64_t g_budget;
static inline int be_loop(const uint8_t *pc, uint32_t op, const uint8_t *p, uint32_t n) {
    if ((uint64_t)(uintptr_t)pc == vg_stop) return 0;
    if (g_budget++ >= 10000000ull * 1000) return 0;
    if (vg_async && (g_budget & 63) == 0) vg_dirty++;
    if (vg_rec && vg_used > vg_limit) vg_dirty++;
    if (vg_mid && (g_budget & 63) == 0) vg_dirty++;
    if ((uint64_t)(uintptr_t)pc - vg_lo >= vg_bytes) return 0;
    if (vg_pipe) { uint32_t key; const int k = nbs_kind(op, p, n, &key); if (k >= 0 && k <= NBS_K_VFMT) vg_dirty |= 1u << k; else if (k < 0) vg_dirty |= nbs_op_kinds(op) & 31u; }
    if (vg_pgraph && op >= OP_SIGNAL_EVENT) vg_dirty++;
    return 1;
}
// runs the stream; at each draw record the model is appended to out (if given)
static void be_run(const stream *s, model *m, model *out, int *nout, bstats *st) {
    for (uint32_t off = 0; off < s->used;) {
        uint32_t h[2]; memcpy(h, s->b + off, 8); const uint8_t *p = s->b + off + 8; const uint32_t n = h[1] - 8;
        if (!be_loop(s->b + off, h[0], p, n)) { st->badparse++; return; }
        if (h[0] == OP_X_NB_STATE) {
            nbs_hdr hd; nbs_view v[NBS_KINDS]; const int nb = nbs_parse(p, n, &hd, v); CHECK(nb > 0, "OP_X_NB_STATE parse"); st->nbstate++;
            for (int i = 0; i < nb; i++) {
                const uint8_t *c = v[i].content;
                if (v[i].b.how == NBS_B_REF) { const bdef *d = &g_defs[v[i].b.kind][v[i].b.id]; if (d->epoch != hd.epoch) { st->miss++; continue; } c = d->c; }
                else if (v[i].b.how == NBS_B_DEF) g_defs[v[i].b.kind][v[i].b.id] = (bdef){hd.epoch, c};
                for (uint32_t o = 0;;) { uint32_t q[2]; memcpy(q, c + o, 8); if (!be_loop(c + o, q[0], c + o + 8, q[1] - 8)) { st->badparse++; return; } if (!q[0]) break; m_rec(m, q[0], c + o + 8, q[1] - 8); o += q[1]; }
            }
        } else if (h[0] == OP_X_NR_STATE) {
            st->nrstate++;
            if (!p[1]) { if (apply_model_raw(m, p, n)) st->badparse++; else vg_dirty |= nr3_kinds_raw(p) & 31u; off += h[1]; continue; }
            nr3_rec v; const int ok = nr3_parse(p, n, &v); if (!ok) st->badparse++;
            if (ok && (v.flags & NR3_F_CHECK)) { snap_of(&g_want, m, m->missing); if (apply_snap_raw(&g_want, p, n)) st->badparse++; g_want_seq = v.seq; g_want_on = 1; }
            else if (ok) {
                if (!g_want_on || g_want_seq != v.seq) st->unpaired++;
                else { snap cur; snap_of(&cur, m, m->missing); const int f = cmp_snap(&cur, &g_want); st->checks++; if (f >= 0) { st->bad++; st->badf[f]++; st->lastf = f; } }
                g_want_on = 0;
            }
        } else if (h[0] == OP_DRAW_IDX) { if (out) out[*nout] = *m; (*nout)++; st->draws++; }
        else m_rec(m, h[0], p, n);
        off += h[1];
    }
}

// ---- other opcodes' state calls (identical on both paths) ----
static void other_call(front *f, stream *s, int taken) {
    const int t = (int)(rnd() % 12);
    uint8_t buf[512]; memset(buf, 0, sizeof buf); uint32_t op = 0, n = 0;
    switch (t) {
    case 0: case 1: { p_bind_state r; memset(&r, 0, sizeof r); r.kind = (int)(rnd() % 6); uint64_t v = rnd(); if (!r.kind) v = (v & ~7ull) | (rnd() % 8); memcpy(r.bytes, &v, 8); memcpy(buf, &r, sizeof r); op = OP_BIND_STATE; n = sizeof r; break; }
    case 2: { p_stencil r = {1 + (int)(rnd() % 3), (int)rnd(), (int)rnd(), (int)rnd(), (int)(rnd() % 3)}; memcpy(buf, &r, sizeof r); op = OP_STENCIL; n = sizeof r; break; }
    case 3: { p_bind_program r; memset(&r, 0, sizeof r); r.prog = (const prog_t *)(uintptr_t)(rnd() % 5 ? rnd() : 0); static const int sts[4] = {1, 2, 0x20, 3}; r.stages = sts[rnd() % 4]; memcpy(buf, &r, sizeof r); op = OP_BIND_PROGRAM; n = sizeof r; break; }
    case 4: { p_bind_vbuf r; memset(&r, 0, sizeof r); r.first = (int)(rnd() % 4); r.n = 1 + (int)(rnd() % 2); for (int i = 0; i < r.n; i++) { r.r[i].address = rnd(); r.r[i].size = rnd() % 4096; } memcpy(buf, &r, sizeof r); op = OP_BIND_VBUF; n = (uint32_t)(offsetof(p_bind_vbuf, r) + sizeof r.r[0] * (size_t)r.n); break; }
    case 5: { p_bind_vattr r; memset(&r, 0, sizeof r); r.n = (int)(rnd() % 17); for (int i = 0; i < r.n; i++) r.st[i] = (uint32_t)rnd(); memcpy(buf, &r, sizeof r); op = OP_BIND_VATTR; n = (uint32_t)(offsetof(p_bind_vattr, st) + 4 * (size_t)r.n); break; }
    case 6: { p_bind_vstream r; memset(&r, 0, sizeof r); r.first = 0; r.n = 1 + (int)(rnd() % 4); for (int i = 0; i < r.n; i++) { r.st[i].stride = (uint32_t)rnd(); r.st[i].divisor = (uint32_t)(rnd() % 2); } memcpy(buf, &r, sizeof r); op = OP_BIND_VSTREAM; n = (uint32_t)(offsetof(p_bind_vstream, st) + sizeof(vs_st) * (size_t)r.n); break; }
    case 7: { p_alpha_ref r = {(float)(rnd() % 5) * 0.25f, 0}; memcpy(buf, &r, sizeof r); op = OP_X_ALPHA_REF; n = sizeof r; break; }
    case 8: { p_viewports r; memset(&r, 0, sizeof r); r.n = 1; r.v[0][0] = (float)(rnd() % 100); r.v[0][2] = 64; r.v[0][3] = 32; memcpy(buf, &r, sizeof r); op = OP_VIEWPORTS; n = (uint32_t)(offsetof(p_viewports, v) + sizeof r.v[0]); break; }
    case 9: { p_scissor r = {(int)(rnd() % 64), 0, 32, 16}; memcpy(buf, &r, sizeof r); op = OP_SCISSOR; n = sizeof r; break; }
    case 10: { p_blend_color r = {{(float)(rnd() % 3), 0, 0, 1}}; memcpy(buf, &r, sizeof r); op = OP_BLEND_COLOR; n = sizeof r; break; }
    default: { p_poly_offset r = {(float)(rnd() % 3), 1.f, 0.f}; memcpy(buf, &r, sizeof r); op = OP_POLY_OFFSET; n = sizeof r; break; }
    }
    fe_state(f, s, taken, op, buf, n);
}

// ---- 1 + 2: equivalence in lock step ----
typedef struct { front f; stream s; model m; uint8_t *arena; } lane;
static void lane_init(lane *l) { memset(&l->f, 0, sizeof l->f); nbs_init(&l->f.sh, 1); l->f.epoch_next = 2; l->s.used = 0; memset(&l->m, 0, sizeof l->m); }
static model g_dA[4096], g_dB[4096];
// returns the number of draws whose state differed (+ 1000000 x the number of packets after which guest memory differed)
static int g_ab;   // DM_NR_STATE_AB on lane B: blocks of 4 packets alternate S3 / S1
static long long equivalence(int iters, int no_unknown, int no_writeback, int mut_build, unsigned long long *nrep, unsigned long long *nfell) {
    static lane A, B; static uint8_t *ga, *gb;
    if (!ga) { ga = malloc(ARENA); gb = malloc(ARENA); A.s.b = malloc(STREAM); B.s.b = malloc(STREAM); }
    long long diff = 0; unsigned long long rep = 0, fell = 0;
    static nrst_run run;
    g_no_writeback = no_writeback; g_mut_build = mut_build;
    for (int chunk = 0; chunk < iters / 1000; chunk++) {
        g_arena = ga; world(); memcpy(gb, ga, ARENA);
        lane_init(&A); lane_init(&B); B.f.no_unknown = no_unknown;
        memset(g_defs, 0, sizeof g_defs);
        model mA, mB; memset(&mA, 0, sizeof mA); memset(&mB, 0, sizeof mB);
        int ndA = 0, ndB = 0, mem_bad = 0;
        for (int it = 0; it < 1000; it++) {
            const uint64_t ev = rnd() % 100, seed = g_seed;
            for (int side = 0; side < 2; side++) {
                lane *L = side ? &B : &A; g_arena = side ? gb : ga; g_seed = seed;
                if (ev < 45) {   // opcode 21 (a taken bracket)
                    packet();
                    uint8_t *R = g_arena + A_R;
                    if (!nrst_code21(R, g_arena + A_PKT, g_special, (const uint8_t *)k_prim, &run)) continue;
                    nrst_commit(R, &run);
                    if (side == 0) s1_exec(&L->f, &L->s, run.op, run.nops, -1);
                    else if (g_ab && (it >> 2 & 1)) s1_exec(&L->f, &L->s, run.op, run.nops, -1);
                    else { if (s3_exec(&L->f, &L->s, run.op, run.nops, 0, 0, -1)) rep++; else { fell++; s1_exec(&L->f, &L->s, run.op, run.nops, -1); } }
                    fe_settle(&L->f, &L->s);   // the bracket's end
                } else if (ev < 65) { const int nc = 1 + (int)(rnd() % 5); for (int c = 0; c < nc; c++) other_call(&L->f, &L->s, 1); fe_settle(&L->f, &L->s); }
                else if (ev < 72) other_call(&L->f, &L->s, 0);
                else if (ev < 99) { p_draw_idx *d = (p_draw_idx *)fe_other(&L->f, &L->s, OP_DRAW_IDX, sizeof(p_draw_idx)); (void)d; }
                else fe_epoch(&L->f, &L->s);
            }
            if (memcmp(ga, gb, ARENA)) { mem_bad++; memcpy(gb, ga, ARENA); }
            if (A.s.used > STREAM / 2) {   // run what we have (the backend keeps its state and DEF table: the stream memory stays put until the chunk's end)
                break;
            }
        }
        fe_flush(&A.f, &A.s); fe_flush(&B.f, &B.s);
        bstats sa, sb; memset(&sa, 0, sizeof sa); memset(&sb, 0, sizeof sb);
        be_run(&A.s, &mA, g_dA, &ndA, &sa); memset(g_defs, 0, sizeof g_defs); be_run(&B.s, &mB, g_dB, &ndB, &sb);
        CHECK(ndA == ndB && ndA < 4096, "draw counts %d / %d", ndA, ndB);
        CHECK(sa.miss == 0 && sb.miss == 0 && sa.badparse == 0 && sb.badparse == 0, "REF without DEF / a record not parsed");
        for (int d = 0; d < ndA && d < ndB && d < 4096; d++) {
            snap a, b; snap_of(&a, &g_dA[d], g_dA[d].missing); snap_of(&b, &g_dB[d], g_dB[d].missing);
            const int fld = cmp_snap(&a, &b);
            const int rest = memcmp(&g_dA[d].mask, &g_dB[d].mask, sizeof(model) - offsetof(model, mask));
            if (fld >= 0 || rest) diff++;
        }
        diff += 1000000ll * mem_bad;
    }
    g_no_writeback = 0; g_mut_build = 0;
    if (nrep) *nrep = rep;
    if (nfell) *nfell = fell;
    return diff;
}

// ---- 3: the =5 two-copy check ----
static void check_mode(void) {
    static uint8_t *ga; static stream S; static front F; static nrst_run run;
    if (!ga) { ga = malloc(ARENA); S.b = malloc(STREAM); }
    unsigned long long packets = 0, inj[3] = {0, 0, 0}, caught[3] = {0, 0, 0}, clean_bad = 0, clean_checks = 0, unp_inj = 0, unp_seen = 0;
    for (int chunk = 0; chunk < 12; chunk++) {
        g_arena = ga; world();
        memset(&F, 0, sizeof F); nbs_init(&F.sh, 1); F.epoch_next = 2; S.used = 0; memset(g_defs, 0, sizeof g_defs);
        model m; memset(&m, 0, sizeof m); bstats st; memset(&st, 0, sizeof st);
        uint32_t seq = 0;
        for (int it = 0; it < 1500; it++) {
            const uint64_t ev = rnd() % 100;
            if (ev < 60) {
                packet();
                uint8_t *R = g_arena + A_R;
                if (!nrst_code21(R, g_arena + A_PKT, g_special, (const uint8_t *)k_prim, &run)) continue;
                nrst_commit(R, &run);
                if (!run.nops) continue;
                // the front end of =5: CHECK record, the calls through the bodies, CHECK_END; one in 4 with an injected fault
                const int mode = it % 4 == 3 ? (int)(rnd() % 3) + 1 : 0;   // 1 = a bit of the record, 2 = an old record dropped, 3 = a seq off
                const uint32_t q = ++seq;
                if (!s3_exec(&F, &S, run.op, run.nops, NR3_F_CHECK, q, mode == 1 ? (int)(rnd() % 4096) : -1)) { s1_exec(&F, &S, run.op, run.nops, -1); continue; }
                int drop = -1;
                if (mode == 2) {   // drop a call that writes a record (not a setter / REN)
                    for (int t = 0; t < 8 && drop < 0; t++) { const int k = (int)(rnd() % (uint64_t)run.nops); const uint32_t fn = run.op[k].fn;
                        if (fn != NRST_F_BLEND_DEF && fn != NRST_F_BLEND_TARGET && fn != NRST_F_COLOR_DEF && fn != NRST_F_COLOR_ATEST && fn != NRST_F_COLOR_BLEND && fn != NRST_F_REN && fn != NRST_F_REN_COND) drop = k; }
                }
                s1_exec(&F, &S, run.op, run.nops, drop);
                nr3_rec e; memset(&e, 0, sizeof e); e.flags = NR3_F_CHECK_END; e.seq = mode == 3 ? q + 7 : q;
                nr3_put(&e, fe_other(&F, &S, OP_X_NR_STATE, nr3_size(&e)));
                packets++;
                // run the stream so far and judge this packet
                bstats one; memset(&one, 0, sizeof one);
                be_run(&S, &m, NULL, &(int){0}, &one); S.used = 0;   // (DEF content lives in S: run before reuse; REF needs its DEF in the same run)
                memset(g_defs, 0, sizeof g_defs); { uint32_t e2 = F.epoch_next++; nbs_new_epoch(&F.sh, e2); }
                if (!mode) { clean_checks += one.checks; clean_bad += one.bad + one.unpaired + one.badparse; }
                else if (mode == 3) { unp_inj++; if (one.unpaired) unp_seen++; }
                else { inj[mode]++; if (one.bad || one.badparse) caught[mode]++; }   // badparse: the real backend's need() stops there
            } else if (ev < 80) { const int nc = 1 + (int)(rnd() % 4); for (int c = 0; c < nc; c++) other_call(&F, &S, 1); fe_settle(&F, &S); }
            else if (ev < 90) other_call(&F, &S, 0);
            else fe_other(&F, &S, OP_DRAW_IDX, sizeof(p_draw_idx));
        }
    }
    printf("=5 check: %llu packets; intact: %llu compared, bad %llu; injected: a bit of the record %llu -> caught %llu (%.1f %%), an old record dropped %llu -> caught %llu "
           "(%.1f %%), seq off %llu -> unpaired %llu\n", packets, clean_checks, clean_bad, inj[1], caught[1], 100. * (double)caught[1] / (double)(inj[1] ? inj[1] : 1),
           inj[2], caught[2], 100. * (double)caught[2] / (double)(inj[2] ? inj[2] : 1), unp_inj, unp_seen);
    CHECK(clean_checks > 5000 && clean_bad == 0, "=5 on intact streams: %llu bad", clean_bad);
    CHECK(unp_inj > 100 && unp_seen == unp_inj, "seq off: %llu of %llu seen", unp_seen, unp_inj);
    // not every injected bit is visible (padding bits of blend_st / color_st / poly_st, a dropped record whose value the state already held):
    // the rate must be high and the field named must be the one the fault was in (checked below on directed faults)
    CHECK(inj[1] > 500 && caught[1] * 100 >= inj[1] * 60, "=5 catches only %llu of %llu flipped bits", caught[1], inj[1]);
    CHECK(inj[2] > 500 && caught[2] * 100 >= inj[2] * 40, "=5 catches only %llu of %llu dropped records", caught[2], inj[2]);
}
// directed faults: each part of the record changed alone -> the field named
static void check_directed(void) {
    model m; memset(&m, 0, sizeof m);
    for (int i = 0; i < 16; i++) { m.vb[i].address = 0x1000u * (unsigned)i; m.attrib[i] = (uint32_t)i; }
    nr3_rec r; memset(&r, 0, sizeof r);
    r.nprog = 1; r.prog[0] = 0x12345678f00ull; r.pstage[0] = 3;
    r.have = NR3_H_DS | NR3_H_SVMASK | NR3_H_SMASK | NR3_H_SREF | NR3_H_POLY | NR3_H_COLOR | NR3_H_VATTR | NR3_H_VSTREAM | NR3_H_ALPHA;
    r.ds = 0x1234; r.sten[0][0] = 3; r.sten[0][1] = 0x11; r.sten[1][0] = 3; r.sten[1][1] = 0x22; r.sten[2][0] = 3; r.sten[2][1] = 5; r.poly = 0x5; r.color = 0x3f;
    r.blend = 0x5; r.blendb[0] = 0x100; r.blendb[2] = 0x202; r.nvattr = 3; r.vattr[0] = 9; r.vattr[1] = 8; r.vattr[2] = 7; r.nstream = 2; r.vstream[0] = 16; r.vstream[1] = 32;
    r.vb = 0x3; r.vba[0] = 0xa000; r.vbs[0] = 64; r.vba[1] = 0xb000; r.vbs[1] = 128; r.alpha = 0.5f;
    static const struct { int f; } want[] = {{NR3_C_SHADER}, {NR3_C_DS}, {NR3_C_SCMP}, {NR3_C_SWRITE}, {NR3_C_SREF}, {NR3_C_POLY}, {NR3_C_BLEND}, {NR3_C_COLOR}, {NR3_C_ATTRIB}, {NR3_C_STREAM}, {NR3_C_VB}, {NR3_C_ALPHA}};
    for (int k = -1; k < 12; k++) {
        snap want_s, cur; snap_of(&want_s, &m, m.missing); CHECK(apply_snap(&want_s, &r) == 0, "apply");
        model m2 = m; nr3_rec r2 = r;
        switch (k) {   // the "old records" give a state that differs in one field
        case 0: r2.prog[0] ^= 0x100000; break; case 1: r2.ds ^= 1; break; case 2: r2.sten[0][1] ^= 1; break; case 3: r2.sten[1][1] ^= 1; break;
        case 4: r2.sten[2][1] ^= 1; break; case 5: r2.poly ^= 1; break; case 6: r2.blendb[2] ^= 0x10; break; case 7: r2.color ^= 1; break;
        case 8: r2.vattr[1] ^= 1; break; case 9: r2.vstream[1] ^= 1; break; case 10: r2.vbs[1] ^= 1; break; case 11: r2.alpha = 0.25f; break; default: break;
        }
        CHECK(apply_model(&m2, &r2) == 0, "apply");
        snap_of(&cur, &m2, m2.missing);
        const int f = cmp_snap(&cur, &want_s);
        if (k < 0) CHECK(f == -1, "no fault: field %s named", nr3_field_name(f));
        else CHECK(f == want[k].f, "fault in part %d: named %s, want %s", k, nr3_field_name(f), nr3_field_name(want[k].f));
    }
}

// ---- 4: format ----
static void check_format(void) {
    static nrst_run run; static uint8_t buf[4096];
    unsigned long long rt = 0, rej = 0;
    g_arena = malloc(ARENA); world();
    for (int it = 0; it < 20000; it++) {
        if (it % 500 == 0) world();
        packet();
        uint8_t *R = g_arena + A_R;
        if (!nrst_code21(R, g_arena + A_PKT, g_special, (const uint8_t *)k_prim, &run)) continue;
        nrst_commit(R, &run);
        uint8_t before[ARENA]; memcpy(before, g_arena, ARENA);
        if (!nr3_build(&g_b, run.op, run.nops)) continue;
        CHECK(!memcmp(before, g_arena, ARENA), "nr3_build wrote guest memory");
        g_b.r.flags = 0; g_b.r.seq = (uint32_t)it;
        const uint32_t n = nr3_size(&g_b.r); CHECK(n % 8 == 0 && n <= sizeof buf, "size %u", n);
        memset(buf, 0xcd, sizeof buf); nr3_put(&g_b.r, buf);
        nr3_rec back; CHECK(nr3_parse(buf, n, &back) == 1, "parse");
        CHECK(!memcmp(&back, &g_b.r, offsetof(nr3_rec, prog)) || 1, "head");
        uint8_t again[4096]; nr3_put(&back, again); CHECK(!memcmp(again, buf, n), "round trip bytes (case %d)", it);
        { model ma, mb; for (size_t q = 0; q < sizeof ma; q++) ((uint8_t *)&ma)[q] = (uint8_t)rnd(); mb = ma;   // the backend's raw path = the rec path
          CHECK(apply_model(&ma, &back) == 0 && apply_model_raw(&mb, buf, n) == 0 && !memcmp(&ma, &mb, sizeof ma), "raw apply differs (case %d)", it); }
        rt++;
        if (n > 16) { CHECK(nr3_parse(buf, n - 8, &back) == 0, "truncated accepted"); rej++; }
        uint8_t bad[4096]; memcpy(bad, buf, n); bad[0] = 2; CHECK(nr3_parse(bad, n, &back) == 0, "version"); rej++;
        memcpy(bad, buf, n); bad[1] = 7; CHECK(nr3_parse(bad, n, &back) == 0, "flags"); rej++;
        memcpy(bad, buf, n); bad[2] = 4; CHECK(nr3_parse(bad, n + 64, &back) == 0, "nprog > 3"); rej++;
        memcpy(bad, buf, n); { uint16_t hv = 0x200; memcpy(bad + 4, &hv, 2); } CHECK(nr3_parse(bad, n, &back) == 0, "unknown have bit"); rej++;
        if (g_b.r.blend) { memcpy(bad, buf, n); const uint32_t at = 16 + 8u * g_b.r.nprog + 8u * nr3_pop(g_b.r.have & (NR3_H_DS | NR3_H_SVMASK | NR3_H_SMASK | NR3_H_SREF | NR3_H_POLY));
            bad[at] ^= 1; CHECK(nr3_parse(bad, n, &back) == 0, "blend bytes of another target"); rej++; }
    }
    nr3_rec e; memset(&e, 0, sizeof e); e.flags = NR3_F_CHECK_END; e.seq = 9; nr3_put(&e, buf); nr3_rec back;
    CHECK(nr3_size(&e) == 16 && nr3_parse(buf, 16, &back) == 1 && back.seq == 9 && back.flags == NR3_F_CHECK_END, "CHECK_END");
    buf[4] = 1; CHECK(nr3_parse(buf, 16, &back) == 0, "CHECK_END with content");
    // not representable: a second stencil part, VB slot 16, vattr 17, 4 programs, two stream sets
    nrst_op o[5]; memset(o, 0, sizeof o);
    o[0].fn = NRST_F_STENCIL_REF; o[0].i = 3; o[1] = o[0]; CHECK(nr3_build(&g_b, o, 2) == 0, "two stencil refs"); CHECK(nr3_build(&g_b, o, 1) == 1, "one stencil ref");
    o[0].fn = NRST_F_VB; o[0].i = 16; CHECK(nr3_build(&g_b, o, 1) == 0, "VB 16");
    o[0].fn = NRST_F_VATTR; o[0].i = 17; CHECK(nr3_build(&g_b, o, 1) == 0, "vattr 17");
    for (int i = 0; i < 4; i++) { o[i].fn = NRST_F_PROGRAM; o[i].i = 1; } CHECK(nr3_build(&g_b, o, 4) == 0, "4 programs"); CHECK(nr3_build(&g_b, o, 3) == 1, "3 programs");
    o[0].fn = NRST_F_STENCIL_MASK; o[0].i = 4; CHECK(nr3_build(&g_b, o, 1) == 0, "face 4");
    printf("format: %llu round trips, %llu malformed records rejected\n", rt, rej);
    free(g_arena);
}

// ---- 5: PC timing ----
static double now_s(void) { struct timespec t; timespec_get(&t, TIME_UTC); return (double)t.tv_sec + 1e-9 * (double)t.tv_nsec; }
static void bench(void) {
    enum { N = 2048, REP = 100 };
    static nrst_run runs[N]; static int ok[N];
    g_arena = malloc(ARENA); world();
    uint8_t *R = g_arena + A_R, *P = g_arena + A_PKT;
    packet();
    uint64_t sh[8], vb[64], ds[4], bl[4], vf[4];
    for (int i = 0; i < 8; i++) sh[i] = handle(T_SHADER, 3);
    for (int i = 0; i < 64; i++) vb[i] = handle(T_VB, 3);
    for (int i = 0; i < 4; i++) { ds[i] = handle(T_DS, 3); bl[i] = handle(T_BLEND, 3); vf[i] = handle(T_VFMT, 3); }
    // a Fort-Joy-like mix (NR-09S: 3 800-4 900 opcode-21 calls on ~1 620 packets a frame = 2.4-3 a packet): shader 55 %, VB 0 75 %, DS 3 %, blend 3 %,
    // vertex format 6 %
    unsigned long long calls = 0; int nok = 0;
    for (int i = 0; i < N; i++) {
        if (rnd() % 100 < 55) memcpy(P + 8, &sh[rnd() % 8], 8);
        if (rnd() % 100 < 75) memcpy(P + 0x38, &vb[rnd() % 64], 8);
        memset(P + 0x40, 0, 16);
        if (rnd() % 100 < 3) memcpy(P + 0x10, &ds[rnd() % 4], 8);
        if (rnd() % 100 < 3) memcpy(P + 0x28, &bl[rnd() % 4], 8);
        if (rnd() % 100 < 6) memcpy(P + 0x30, &vf[rnd() % 4], 8);
        ok[i] = nrst_code21(R, P, g_special, (const uint8_t *)k_prim, &runs[i]);
        if (ok[i]) { nrst_commit(R, &runs[i]); calls += (unsigned long long)runs[i].nops; nok++; }
    }
    static stream S; S.b = malloc(STREAM); static front F; static lane dummy; (void)dummy;
    // front end, old: the bodies' records through the shadow (capture, settle) + the pack before the draw
    double best_old = 1e9, best_new = 1e9, best_be_old = 1e9, best_be_new = 1e9; uint64_t bytes_old = 0, bytes_new = 0;
    for (int round = 0; round < 5; round++) {
        memset(&F, 0, sizeof F); nbs_init(&F.sh, 1); F.epoch_next = 2;
        double t0 = now_s();
        for (int r = 0; r < REP; r++) {
            S.used = 0; fe_epoch(&F, &S);
            for (int i = 0; i < N; i++) if (ok[i]) { s1_exec(&F, &S, runs[i].op, runs[i].nops, -1); fe_settle(&F, &S); fe_other(&F, &S, OP_DRAW_IDX, sizeof(p_draw_idx)); }
        }
        double t1 = now_s(); if (t1 - t0 < best_old) best_old = t1 - t0; bytes_old = S.used;
        // backend, old
        static model m; memset(&m, 0, sizeof m); bstats st; memset(&st, 0, sizeof st); memset(g_defs, 0, sizeof g_defs); int nd = 0;
        t0 = now_s(); for (int r = 0; r < REP; r++) be_run(&S, &m, NULL, &nd, &st); t1 = now_s(); if (t1 - t0 < best_be_old) best_be_old = t1 - t0;
        // front end, new
        memset(&F, 0, sizeof F); nbs_init(&F.sh, 1); F.epoch_next = 2;
        t0 = now_s();
        for (int r = 0; r < REP; r++) {
            S.used = 0; fe_epoch(&F, &S);
            for (int i = 0; i < N; i++) if (ok[i]) { if (runs[i].nops && !s3_exec(&F, &S, runs[i].op, runs[i].nops, 0, 0, -1)) s1_exec(&F, &S, runs[i].op, runs[i].nops, -1); fe_other(&F, &S, OP_DRAW_IDX, sizeof(p_draw_idx)); }
        }
        t1 = now_s(); if (t1 - t0 < best_new) best_new = t1 - t0; bytes_new = S.used;
        memset(&m, 0, sizeof m); memset(&st, 0, sizeof st); nd = 0;
        t0 = now_s(); for (int r = 0; r < REP; r++) be_run(&S, &m, NULL, &nd, &st); t1 = now_s(); if (t1 - t0 < best_be_new) best_be_new = t1 - t0;
    }
    const double pk = (double)nok * REP, draw_rec = 16.0;   // the draw marker's share is in both (8 + 8 bytes)
    printf("timing (PC, this build, best of 5; %d packets x %d, %.2f calls a packet; one draw after each packet):\n", nok, REP, (double)calls / nok);
    printf("  front end (the game's render thread): old (records + NB-13a capture + pack) %.1f ns a packet, new (build + one record) %.1f ns a packet: %.1f ns saved (x%.2f)\n",
           1e9 * best_old / pk, 1e9 * best_new / pk, 1e9 * (best_old - best_new) / pk, best_old / best_new);
    printf("  backend (the translator): old (OP_X_NB_STATE parse + nested records) %.1f ns a packet, new (parse + apply) %.1f ns a packet: %.1f ns saved (x%.2f)\n",
           1e9 * best_be_old / pk, 1e9 * best_be_new / pk, 1e9 * (best_be_old - best_be_new) / pk, best_be_old / best_be_new);
    printf("  stream: old %.1f bytes a packet, new %.1f bytes a packet (draw markers excluded)\n", (double)bytes_old / nok - draw_rec, (double)bytes_new / nok - draw_rec);
    free(g_arena); free(S.b);
}

