static const uint32_t k_nvn_stage[6] = {0, 3, 4, 2, 1, 5};   // xbg_game.cpp nvn_stage
// OP_BIND_PROGRAM: the stages' shaders cleared, then the program's (here derived from the pointer), missing if one of them is absent
static void m_bind(uintptr_t *shader, int *missing, uint64_t prog, int stages) {
    for (unsigned st = 0; st < 6; st++) if (stages & (1u << k_nvn_stage[st])) shader[st] = 0;
    if (!prog) return;
    *missing = 0;
    const unsigned nst = 1 + (unsigned)(prog >> 7 & 3);
    for (unsigned i = 0; i < nst; i++) {
        const unsigned st = (unsigned)((prog >> (12 + 3 * i)) % 6);
        if ((prog >> (20 + i) & 15) == 0) { *missing = 1; continue; }
        if (stages & (1u << k_nvn_stage[st])) shader[st] = (uintptr_t)(prog ^ (0x9e37u * (st + 1)));
    }
}
