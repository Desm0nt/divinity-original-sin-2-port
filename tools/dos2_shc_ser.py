#!/usr/bin/env python3
"""[DOS2] NR-NATIVE shadows (DM_NRN_SHC): hash_ser() of dm/gfx/vulkan/engine/xbg_nr_shc.inc is hash() with every word it mixes into the
structure hash written to a tape instead (SM / SB). This tool derives hash_ser() from the text of hash() mechanically, so the two can
never read different inputs:

    python tools/dos2_shc_ser.py --write    rewrite the generated block in xbg_nr_shc.inc
    python tools/dos2_shc_ser.py --check    exit 0 when the block in the file is what hash() gives now (the structure test runs this)
"""
import io
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'dm/gfx/vulkan/engine/xbg_nr_shc.inc'
BEGIN = '// ---- generated by tools/dos2_shc_ser.py from hash(): do not edit ----'
END = '// ---- end of the generated block ----'
HEAD = 'uint64_t hash(int prim,int first,int count,const p_draw_idx *ix,uint32_t inst,uint32_t first_inst,bool gi,int &tw,uint64_t &hs,bool wv,Ver &V){'
STOP = '// ---- the range ----'
CR, LF = chr(13) + chr(10), chr(10)


def call_end(t, i):
    """index right after the parenthesis that closes the call opened just before t[i]"""
    depth = 1
    while depth:
        c = t[i]
        depth += c == '('
        depth -= c == ')'
        i += 1
    return i


def swap(t, old, new):
    """every `h=<fn>(h,ARGS);` -> `<new>(ARGS);`"""
    out, at = [], 0
    while True:
        k = t.find(old, at)
        if k < 0:
            out.append(t[at:])
            return ''.join(out)
        e = call_end(t, k + len(old))
        out.append(t[at:k] + new + '(' + t[k + len(old):e])
        at = e


def derive(body):
    t = body
    first = 'uint64_t h=nrshc_mix(0x53484331,uint64_t(uint32_t(prim))|uint64_t(uint32_t(count))<<32);'
    assert t.count(first) == 1, 'hash(): the first mix moved'
    t = t.replace(first, 'ser_begin();SM(uint64_t(uint32_t(prim))|uint64_t(uint32_t(count))<<32);')
    t = swap(t, 'h=nrshc_mix(h,', 'SM')
    t = swap(t, 'h=nrshc_bytes(h,', 'SB')
    last = 'hs=h;return nrshc_mix(h,hu);}'
    assert t.count(last) == 1, 'hash(): the end moved'
    t = t.replace(last, 'hs=ser_end();return nrshc_mix(hs,hu);}')
    for a, b in (('uint64_t hu=0x55424f;ncu=0;', 'uint64_t hu=0x55424f;if(!dry)ncu=0;'), ('if(R.diag && ncu<', 'if(!dry && R.diag && ncu<'),
                 ('{if(!tw)nrs_last=nw;taint(NRSHC_T_ORDER);}', '{if(!tw && !dry)nrs_last=nw;taint(NRSHC_T_ORDER);}')):
        assert t.count(a) == 1, 'hash(): moved: ' + a
        t = t.replace(a, b)
    assert 'nrshc_mix(h,' not in t and 'nrshc_bytes(h,' not in t and '=h;' not in t and '(h)' not in t, 'hash(): a use of h the tool does not know'
    assert t.startswith(HEAD)
    t = t.replace(HEAD, HEAD.replace('uint64_t hash(', 'uint64_t hash_ser(').replace('bool wv,Ver &V){', 'bool wv,Ver &V,bool dry){'), 1)
    return t


def main():
    raw = io.open(SRC, encoding='utf-8', newline='').read()
    crlf = CR in raw
    t = raw.replace(CR, LF)
    a = t.index(HEAD)
    b = t.index(BEGIN) if BEGIN in t else t.index(STOP)
    body = t[a:b].rstrip(LF) + LF
    gen = BEGIN + LF + derive(body) + END + LF
    if BEGIN in t:
        cur = t[t.index(BEGIN):t.index(END) + len(END) + 1]
    else:
        cur = ''
    if '--check' in sys.argv:
        if cur != gen:
            print('hash_ser() is not hash() run through tools/dos2_shc_ser.py: run it with --write')
            return 1
        print('hash_ser() is in step with hash()')
        return 0
    if cur:
        t = t.replace(cur, gen)
    else:
        t = t[:b] + gen + t[b:]
    io.open(SRC, 'w', encoding='utf-8', newline='').write(t.replace(LF, CR) if crlf else t)
    print('written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
